#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Claude API로 학생 메모를 정식 서술형 평가문으로 변환."""
import anthropic

MODEL = "claude-opus-5"

PROMPT_TEMPLATE = """[서술 스타일 규칙]
- 존댓말, 과거형 관찰 서술체(~했습니다/~보였습니다/~관찰되었습니다)를 쓴다.
- 강점과 약점을 함께 균형 있게 서술한다.
- 자세·표정·손동작 등 구체적으로 관찰된 행동을 근거로 든다.
- 학생의 발언이 메모에 있으면 큰따옴표로 인용하고 그 의미를 해석한다.
- 부정적 행동도 비난조가 아닌 관찰·해석 톤으로 쓰고, 가능하면 긍정 요소나 개선 가능성도 덧붙인다.
- 단정 대신 "~것으로 보였습니다", "~을 시사합니다", "~을 확인할 수 있었습니다" 같은 신중한 표현을 쓴다.
- 한 문단, 보통 3~5문장으로 쓴다.
- 메모에 없는 사실·발언·수치는 절대 지어내지 않는다.
- 내용에 학생의 이름은 절대 포함하지 않는다.
- 메모에만 기반하여 서술하겠습니다 같은 부연 설명은 포함하지 않는다.

[스타일 예시] (아래 톤·형식을 따른다)

예시1)
메모: 가장 학생 중 자세, 태도가 우수함. 자발적으로 참여 태도도 좋고 수업 자세도 흐트러짐 없음. 기록지 작성을 위해 노트에 기록하는 모습도 보임
서술: 전체 참여 학생 중 가장 우수한 자세와 태도를 보인 학생으로, 수업 내내 흐트러짐 없이 바른 자세를 유지하며 진지하게 수업에 임했습니다. 자발적으로 적극적인 참여 의지를 드러냈으며, 기록지 작성을 위해 노트에 성실하게 기록하는 모습을 통해 수업 내용을 정리하고 내면화 하려는 책임감 있는 학습 태도가 두드러졌습니다.

예시2)
메모: 조용히 수업에 임하는 모습이나 발문에는 자신의 생각을 명확히 표현하는 태도를 보임
서술: 수업 시간 내내 조용한 태도를 유지하면서도 강사의 발문에 대해서는 자신의 생각을 명확하게 표현하는 모습을 보였습니다. 소극적이지 않으면서도 차분한 수업 태도를 유지했으며, 질문에 응할 때는 신중하고 정돈된 답변을 제시하는 것으로 보아 수업 내용에 대한 충분한 이해가 있음을 확인할 수 있었습니다.

예시3)
메모: 진지하고 성실하며 질문에 손을 들고 발표하는 등 자발적인 참여 모습을 보여줌
서술: 수업 시간 동안 진지하고 성실한 태도로 임하며, 질문에 손을 들고 적극적으로 발표하는 등 자발적이고 주도적인 참여 모습을 보여주었습니다. 이러한 모습은 수업 내용에 대한 관심과 이해하려는 적극적인 학습 의지를 잘 드러냈습니다

예시4)
메모: 5교시에 졸음을 참으려고 노력하였으나 졸려하는 눈빛이 있었음. 지적을 했을때 거부감 없이 수긍하는 자세를 보이고 세수하고 온 후 수업 참여의 적극성도 보이고 생각 표현도 구체적으로 함
서술: 5교시에 졸린 눈빛이 관찰되었고 졸음으로 어려움을 겪었으나 이를 참으려는 노력을 기울였으며, 강사의 지적에 대해서는 거부감 없이 수긍하는 성숙한 태도를 보였습니다. 5교시 이후 세수를 하고 돌아온 뒤에는 수업 참여의 적극성이 두드러지게 증가하였습니다. 특히 강사의 발문에 대해 자신의 생각을 구체적으로 표현하는 모습을 보이며, 지적을 계기로 수업 태도를 개선하려는 의지와 능력을 함께 확인할 수 있었습니다.

예시5)
메모: 수업, 자세 태도 우수함. 발문에 자발적으로 참여하는 모습, 자신의 생각을 표현하는 태도 등 수업에 성실히 임함
서술: 수업 전반에 걸쳐 우수한 자세와 태도를 유지하며 강사의 발문에 자발적으로 참여하는 모습을 보였습니다. 자신의 생각을 구체적이고 적극적으로 표현하고 수업 내용에 성실하게 임하는 태도가 두드러졌으며, 이러한 모습들은 학습에 대한 진지한 자세와 책임감 있는 수업 참여를 잘 드러내고 있었습니다

예시6)
메모: 수업 자세와 태도 우수함. 진지하고 성실히 임하고 수업 대형에서 벗어난 행동은 보이지 않음
서술: 수업 시간 동안 진지하고 성실한 태도로 수업에 임하는 모습을 보였으며, 자세가 우수하고 수업 대형에서 벗어나는 행동을 보이지 않았습니다. 전반적으로 모범적인 수업 태도와 안정적인 학습 자세를 유지하며 수업에 참여하는 학생으로 확인되었습니다.

예시7)
메모: 조는 모습은 없으나 멍한 모습의 자세와 소극적으로 임하는 태도를 보임. 보호처분에 관한 설명을 할 때는 매우 집중하는 모습을 보임
서술: 수업 시간 동안 졸거나 자는 모습은 보이지 않았으나, 멍한 표정과 자세로 전체적으로 소극적인 태도를 유지하고 있었습니다. 그러나 보호처분에 관한 설명이 진행될 때에는 눈에 띄게 집중력을 높이며 매우 진지하게 귀 기울이는 모습을 보여, 자신과 관련된 내용에 대해서는 관심을 가지고 있음을 확인할 수 있었습니다.

[출력]
위 규칙과 톤을 따라, 아래 학생의 메모를 서술 한 문단으로 정리하라. 서술 문장만 출력한다.
이름: {name}
메모: {notes}
"""

_client = anthropic.Anthropic()  # ANTHROPIC_API_KEY 환경변수에서 자동으로 읽음


def generate_evaluation(name: str, notes: str) -> str:
    prompt = PROMPT_TEMPLATE.format(name=name, notes=notes)
    try:
        response = _client.messages.create(
            model=MODEL,
            max_tokens=2048,
            messages=[{"role": "user", "content": prompt}],
        )
    except anthropic.AuthenticationError:
        raise RuntimeError("Claude API 키가 유효하지 않습니다.")
    except anthropic.RateLimitError:
        raise RuntimeError("Claude API 요청 한도를 초과했습니다.")
    except anthropic.APIConnectionError:
        raise RuntimeError("Claude API에 연결할 수 없습니다.")
    except anthropic.APIStatusError as e:
        raise RuntimeError(f"Claude API 오류 ({e.status_code}): {e.message}")

    text = "".join(b.text for b in response.content if b.type == "text").strip()
    if not text:
        raise RuntimeError(f"'{name}' 평가문 생성 결과가 비어 있습니다.")
    return text
